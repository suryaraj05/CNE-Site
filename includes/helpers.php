function section_id(array $s): string
{
    return empty($s['id']) ? '' : ' id="' . e($s['id']) . '"';
}

/** Eyebrow + h2 + optional intro, shared by most sections. */
function section_heading(array $s, string $align = 'left', bool $dark = false): void
{
    $center = $align === 'center';
    if (!empty($s['eyebrow'])) {
        echo '<p class="text-xs font-semibold tracking-[0.14em] uppercase ' . ($dark ? 'text-blue-200' : 'text-navy') . '">' . e($s['eyebrow']) . '</p>';
    }
    if (!empty($s['title'])) {
        echo '<h2 class="mt-3 text-3xl leading-tight font-bold tracking-[-0.025em] text-balance sm:text-4xl ' . ($dark ? 'text-white' : 'text-ink') . '">' . e($s['title']) . '</h2>';
    }
    if (!empty($s['intro'])) {
        echo '<p class="mt-4 max-w-2xl text-[17px] leading-relaxed ' . ($dark ? 'text-blue-100/80' : 'text-muted') . ($center ? ' mx-auto' : '') . '">' . e($s['intro']) . '</p>';
    }
}

/**
 * Optional content image: a path string or ['src', 'alt', 'width', 'height'].
 * Images live in /assets/img/ and are supplied by the site owner.
 */
function img_tag(string|array|null $img, string $class, bool $eager = false): string
{
    if (!$img) return '';
    $img = is_string($img) ? ['src' => $img] : $img;
    $size = isset($img['width'], $img['height']) ? ' width="' . (int) $img['width'] . '" height="' . (int) $img['height'] . '"' : '';
    return '<img src="' . e($img['src']) . '" alt="' . e($img['alt'] ?? '') . '"' . $size
        . ($eager ? ' fetchpriority="high"' : ' loading="lazy"') . ' decoding="async" class="' . e($class) . '">';
}

/** URL of /assets/img/{name}.(svg|png|webp|jpg) if the owner has added it. */
function asset_img(string $name): ?string
{
    foreach (['svg', 'png', 'webp', 'jpg'] as $ext) {
        if (is_file(__DIR__ . "/../assets/img/$name.$ext")) return "/assets/img/$name.$ext";
    }
    return null;
}

function social_links(string $class, string $iconClass = 'size-4'): string
{
    $out = '';
    foreach (SOCIAL as $key => [$label, $url]) {
        $out .= '<a href="' . e($url) . '" target="_blank" rel="noopener" class="' . e($class) . '">'
            . icon($key, $iconClass) . '<span class="sr-only">' . e($label) . '</span></a>';
    }
    return $out;
}
